# Steps to Install Python, Setting up VS Code:

# 1. Download Visual Studio Code ( VS Code):
#    Open a browser
#    Download VS Code for windows
#    Complete the installation

# 2. Open VS Code:
#    Launch VS Code
#    Click file
#    Select Open folder
#    Create a new folder where you want to store python codes

# 3. Create python file:
#    Click New file
#    Type the name of the file with .py extension
#    Save the file

# 4. Install python extensions:
#    Click on extensions in VS Code
#    Search for python
#    Select the required python extensions from VS Code
#    Install them

# 5. Write and run the program
#    Write a simple python program
#    Example: print(“HI”)
#    Save the file
#    Click on run button and run the program in terminal
#    The output will be displayed in the terminal of the VS Code